import * as SQLite from 'expo-sqlite'

/**
 * The library, on the device (#159).
 *
 * > Music is stored on the user's device. The server is not where their music
 * > lives.
 *
 * I has said that at least three times. Today the phone is a thin client
 * streaming from `/songs/{id}/audio`, which means the server holds everyone's
 * music and needs per-install tenancy (#170) to keep them apart. Both of those
 * are consequences of the storage being in the wrong place, not arguments for it.
 *
 * This is the metadata half of moving it: a SQLite database on the phone, holding
 * what the server's `songs` table holds plus where the audio actually is. The
 * audio half is `files.ts`.
 *
 * ## Schema changes without alembic
 *
 * There is no migration tool here, so `PRAGMA user_version` is the version and
 * `MIGRATIONS` is the list. Each entry runs once, in order, inside a transaction.
 * The rules that make that safe are the same ones the backend learned:
 *
 * - **Append only.** Editing a shipped migration changes what a device that
 *   already ran it believes about itself, and nothing will ever tell you.
 * - **Additive where possible.** SQLite cannot drop or retype a column without
 *   rebuilding the table — the same limitation that makes autogenerated alembic
 *   migrations dangerous in this project.
 */

/**
 * Bumped by appending to `MIGRATIONS`, never by editing this number by hand.
 *
 * Exported so a test can run the real statements against a real SQLite rather
 * than assert on their text. A migration that rebuilds a table is exactly the
 * kind the backend learned not to trust by reading (`docs/lessons.md`) — and
 * the failure mode here is a device that cannot open its own library.
 */

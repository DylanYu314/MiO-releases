export const DATABASE_NAME = 'mio-library.db'

let opening: Promise<SQLite.SQLiteDatabase> | null = null

/**
 * The open database, migrated to the current schema.
 *
 * Cached as the *promise*, not the resolved handle, so two callers racing on
 * first launch share one open and one migration rather than both running the
 * schema.
 */
/**
 * Transactions, one at a time, on the one connection every screen shares.
 *
 * ## The bug this exists for (#437)
 *
 * The 2026-08-09 import produced, twice:
 *
 *     playlistImport.trackThrew #106: cannot start a transaction within a transaction
 *     playlistImport.trackThrew  #54: cannot rollback - no transaction is active
 *
 * `openLibraryDb` hands every caller the **same** `SQLiteDatabase`, and
 * `withTransactionAsync` issues `BEGIN` and `COMMIT` on it. SQLite has no
 * nested transactions, so two overlapping callers are not slow — they are an
 * error, and the second message is the first one's `COMMIT` arriving after the
 * failed `BEGIN` already unwound it. One track is lost per collision.
 *
 * It went unseen because nothing reported it: the import loop awaited each
 * track bare, so the throw killed a worker silently. #426 gave it a name, and
 * the very next device pass printed it.
 *
 * ## Why a queue and not `withExclusiveTransactionAsync`
 *
 * That API opens its **own connection** and requires every query inside to be
 * issued against the `txn` object it hands you. A query that keeps using `db`
 * still compiles, still runs, and silently executes *outside* the transaction
 * on the other connection — a worse failure than the one being fixed, and one
 * no test here would catch. Serialising is the smaller claim: the transactions
 * were always meant to be short, and this only stops them interleaving.
 */
let transactions: Promise<unknown> = Promise.resolve()

/**
 * Run `work` inside a transaction, after any transaction already queued.
 *
 * Every transactional write in this app goes through here. Using
 * `db.withTransactionAsync` directly is the bug above.
 *
 * **Takes the database rather than opening one.** The caller already has it,
 * and a helper that called `openLibraryDb` itself would close over the real
 * one — so a test that mocks the connection would still reach native SQLite
 * through this function. That is not hypothetical: it broke fourteen tests the
 * first time this was written.
 */
export async function withLibraryTransaction(
  db: Pick<SQLite.SQLiteDatabase, 'withTransactionAsync'>,
  work: () => Promise<void>,
): Promise<void> {
  const run = transactions.then(() => db.withTransactionAsync(work))
  // A failed transaction must not poison the queue behind it: the next caller
  // is a different track and has done nothing wrong.
  transactions = run.catch(() => undefined)
  return run
}

/** Test seam: the queue is module state and outlives a test. */
export function __resetLibraryTransactions(): void {
  transactions = Promise.resolve()
}

export function openLibraryDb(): Promise<SQLite.SQLiteDatabase> {
  opening ??= SQLite.openDatabaseAsync(DATABASE_NAME)
    .then(async (db) => {
      await migrate(db)
      return db
    })
    .catch((error) => {
      /**
       * Forget a failed open, so the next caller tries again.
       *
       * Caching the *promise* is what makes two callers on first launch share
       * one open and one migration. But a rejected promise is cached just as
       * happily as a resolved one — so a single transient failure poisoned
       * every later call for the rest of the app's life, and only a reload
       * cleared it.
       *
       * That is a bad shape for something every screen depends on: one
       * unlucky moment and the library, playlists and favourites are all
       * broken until the app is restarted, with no way for the user to know
       * restarting is the fix.
       */
      opening = null
      throw error
    })
  return opening
}

/**
 * Bring a database up to the current schema version.
 *
 * Exported so a test can drive it against a throwaway database, which is the
 * only way to find out that a migration does not run — the app would otherwise
 * discover it at launch, on a device, with a user's library inside.
 */
export async function migrate(db: SQLite.SQLiteDatabase): Promise<number> {
  const row = await db.getFirstAsync<{ user_version: number }>('PRAGMA user_version')
  const current = row?.user_version ?? 0

  for (let version = current; version < MIGRATIONS.length; version++) {
    // Each migration and its version bump go together: a crash between them
    // would otherwise leave the schema ahead of the number recording it, and the
    // next launch would run it a second time.
    await db.withTransactionAsync(async () => {
      await db.execAsync(MIGRATIONS[version])
      await db.execAsync(`PRAGMA user_version = ${version + 1}`)
    })
  }

  return MIGRATIONS.length
}

/** Test seam: forget the cached handle so the next call opens afresh. */
export function __resetLibraryDb(): void {
  opening = null
}
